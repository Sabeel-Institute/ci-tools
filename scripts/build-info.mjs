import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Stamp the build: app/src/build-info.ts, with app.json's version and the
 * commit being built, for the `v<version> · <commit>` label each app shows on
 * its sign-in screen.
 *
 *   sabeel-ci build-info
 *
 * The commit is HEAD's short hash, with `+` when the working tree holds
 * uncommitted changes, or `dev` outside a Git checkout. `ci-platform` and
 * `ci-play` look for it in the bundle they ship and refuse it marked `+`;
 * `check-release` reads it off the sign-in screen. The file is generated and
 * gitignored (`check-app`): the app's `prepare` writes it so the code compiles,
 * and `build-web` and `build-aab` write it again just before they bundle, so
 * the commit is the one that ships. A new commit changes the file, so Gradle
 * never reuses a JS bundle stamped with the previous one.
 */
export const BUILD_INFO = 'app/src/build-info.ts';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

/** HEAD's short hash, `+` when the tree is dirty, `dev` without Git. */
export function buildCommit() {
  try {
    const commit = git('rev-parse', '--short', 'HEAD');
    return git('status', '--porcelain') ? `${commit}+` : commit;
  } catch {
    return 'dev';
  }
}

/** Write BUILD_INFO for the working directory's app; unchanged content is left alone. */
export function writeBuildInfo() {
  const { version } = JSON.parse(readFileSync('app/app.json', 'utf8')).expo;
  const commit = buildCommit();
  const text = '// GENERATED by `sabeel-ci build-info` (Sabeel-Institute/ci-tools): do not edit.\n'
    + "// Written at every build; a '+' after the commit marks a build from uncommitted changes.\n"
    + `export const BUILD_INFO = { version: ${JSON.stringify(version)}, commit: ${JSON.stringify(commit)} } as const;\n`;
  if (!existsSync(BUILD_INFO) || readFileSync(BUILD_INFO, 'utf8') !== text) writeFileSync(BUILD_INFO, text);
  return { version, commit };
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  if (process.argv.length > 2) {
    console.error('usage: sabeel-ci build-info');
    process.exit(2);
  }
  const { version, commit } = writeBuildInfo();
  console.log(`${BUILD_INFO}: v${version} · ${commit}`);
}
