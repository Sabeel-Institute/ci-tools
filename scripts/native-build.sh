#!/usr/bin/env bash
set -euo pipefail
# The debug app the native flows install, built into a directory of its own:
#
#   sabeel-ci native-build android <dir>   # <dir>/app-debug.apk, x86_64, for the emulator
#   sabeel-ci native-build ios <dir>       # <dir>/<App>.app, for the iOS simulator (macOS)
#
# A debug build loads its JavaScript from Metro, so what this makes depends
# only on the app's native inputs. The Native workflow keeps it under their
# fingerprint (`native-fingerprint debug`) and runs this only for a new one;
# `native-e2e` runs it when it is given no build. A change here that changes
# what it makes raises RECIPES.debug in native-fingerprint.mjs.

usage="usage: sabeel-ci native-build android|ios <dir>"
[ "$#" -eq 2 ] || { echo "native-build: $usage" >&2; exit 2; }
PLATFORM=$1
case "$PLATFORM" in
  android | ios) ;;
  *) echo "native-build: $usage" >&2; exit 2 ;;
esac
mkdir -p "$2"
OUT=$(cd "$2" && pwd)

if [ "$PLATFORM" = android ]; then
  # Gradle's daemon and a Kotlin compile daemon stay resident after a build,
  # 5 GB between them, beside the emulator, Firebase's emulators and Metro: on
  # a 16 GB runner that ran memory out and GitHub shut the runner down. Kotlin
  # compiles inside Gradle's process, and the daemon stops once the APK exists.
  ( cd app/android \
      && ./gradlew assembleDebug -PreactNativeArchitectures=x86_64 -Pkotlin.compiler.execution.strategy=in-process --quiet \
      && ./gradlew --stop --quiet )
  apk=$(find app/android/app/build/outputs/apk/debug -name '*.apk' | grep -E 'x86_64|app-debug' | head -1)
  [ -n "$apk" ] || { echo "native-build: the build made no debug APK" >&2; exit 1; }
  cp "$apk" "$OUT/app-debug.apk"
  echo "$OUT/app-debug.apk"
  exit 0
fi

# The iOS project is generated by `pods`: a prebuild scoped to iOS (app/ios/ is
# a build product) and the pods the committed Podfile.lock pins. The build
# targets one simulator, as xcodebuild needs, which native-e2e then boots
# (lib/ios-simulator.sh); it need not be running to be built for.
[ "$(uname)" = Darwin ] || { echo "native-build: ios needs macOS and Xcode" >&2; exit 2; }
: "${CI_TOOLS:?run this as sabeel-ci native-build}"
# shellcheck source-path=SCRIPTDIR source=lib/ios-simulator.sh
. "$CI_TOOLS/scripts/lib/ios-simulator.sh"
udid=$(ios_simulator)
bash "$CI_TOOLS/scripts/pods.sh" >&2
workspace=$(find app/ios -maxdepth 1 -name '*.xcworkspace' | head -1)
scheme=$(basename "$workspace" .xcworkspace)
derived=$(mktemp -d "${RUNNER_TEMP:-${TMPDIR:-/tmp}}/native-build-ios.XXXXXX")
xcodebuild -workspace "$workspace" -scheme "$scheme" -configuration Debug -sdk iphonesimulator \
  -destination "id=$udid" -derivedDataPath "$derived" CODE_SIGNING_ALLOWED=NO -quiet build >&2
app=$(find "$derived/Build/Products/Debug-iphonesimulator" -maxdepth 1 -name '*.app' | head -1)
[ -n "$app" ] || { echo "native-build: the build made no .app" >&2; exit 1; }
rm -rf "${OUT:?}/$(basename "$app")"
ditto "$app" "$OUT/$(basename "$app")"
rm -rf "$derived"
echo "$OUT/$(basename "$app")"
